// Package i18n holds the bot's translated messages.
//
// English is the reference language. Any key that is missing in another
// language falls back to English, so translations can be improved or extended
// one string at a time.
package i18n

import "fmt"

// Lang is a supported language.
type Lang struct {
	Code string
	Name string // written in its own language
}

// Langs lists the supported languages in the order shown to users.
var Langs = []Lang{
	{"en", "English"},
	{"hi", "हिन्दी"},
	{"ta", "தமிழ்"},
	{"te", "తెలుగు"},
	{"ml", "മലയാളം"},
	{"kn", "ಕನ್ನಡ"},
}

// Valid reports whether code is a supported language.
func Valid(code string) bool {
	for _, l := range Langs {
		if l.Code == code {
			return true
		}
	}
	return false
}

// Name returns the native name of a language code.
func Name(code string) string {
	for _, l := range Langs {
		if l.Code == code {
			return l.Name
		}
	}
	return "English"
}

// T returns the message for key in lang, formatted with args.
func T(lang, key string, args ...any) string {
	s, ok := table[lang][key]
	if !ok || s == "" {
		s = table["en"][key]
	}
	if s == "" {
		return key
	}
	if len(args) == 0 {
		return s
	}
	return fmt.Sprintf(s, args...)
}

